import 'package:supabase_flutter/supabase_flutter.dart'; // استيراد حزمة سوبابيس الأساسية للتعامل مع خدمات قاعدة البيانات والتخزين السحابي
import 'admin_repository.dart'; // استيراد الواجهة التعريفية (Interface) التي تحدد العقود والمهام البرمجية لمستودع بيانات الأدمن

// استيراد الوحدات (Modules) الفرعية التي تحتوي على التنفيذ الفعلي للوظائف مقسمة حسب التخصص البرمجي لسهولة الصيانة
import 'modules/stats_module.dart'; // استيراد وحدة معالجة الإحصائيات والبيانات الرقمية التي تظهر في لوحة التحكم الرئيسية
import 'modules/users_module.dart'; // استيراد وحدة إدارة حسابات المعلمين والطلاب وعمليات التسجيل والحذف والفلترة حسب الدفعة
import 'modules/circles_module.dart'; // استيراد وحدة إدارة حلقات تحفيظ القرآن الكريم وتوزيع الطلاب والمختبرين عليها
import 'modules/chat_module.dart'; // استيراد وحدة نظام المراسلة الفورية والدردشة وتداول الوسائط بين الإدارة والمستخدمين
import 'modules/progress_module.dart'; // استيراد وحدة متابعة السجلات اليومية، والخطط الدراسية السنوية والشهرية للطلاب
import 'modules/notification_module.dart'; // استيراد وحدة إدارة وإرسال الإشعارات الجماعية والفردية وتتبع سجل الإرسال
import 'modules/reports_module.dart'; // استيراد وحدة استخراج تقارير الحضور والغياب ودرجات الاختبارات والسجلات المعتمدة
import 'modules/holidays_module.dart'; // استيراد وحدة إدارة التقويم الدراسي، الإجازات الرسمية، وطلبات إجازات الطلاب
import 'modules/settings_module.dart'; // استيراد وحدة التحكم في إعدادات النظام العامة مثل تفعيل تسجيل الطلاب ووضع الدفعة

class SupabaseAdminRepository // تعريف الكلاس التنفيذي الرئيسي لمستودع بيانات مدير النظام (الأدمن)
    with // استخدام ميزة "الميكسين" (Mixin) لدمج الوظائف من الوحدات المختلفة في كلاس واحد دون تكرار الكود
        StatsModule, // دمج كافة وظائف جلب ومعالجة إحصائيات النظام في هذا الكلاس
        UsersModule, // دمج كافة وظائف إدارة شؤون المعلمين والطلاب (البحث، الحذف، الفلترة) في هذا الكلاس
        CirclesModule, // دمج كافة وظائف إدارة الحلقات القرآنية وتفاصيلها في هذا الكلاس
        ChatModule, // دمج كافة وظائف نظام الدردشة والمراسلة الفورية في هذا الكلاس
        ProgressModule, // دمج وظائف متابعة تقدم الطلاب الدراسي والخطط التعليمية في هذا الكلاس
        NotificationModule, // دمج وظائف نظام الإشعارات والتواصل الجماعي مع المستخدمين في هذا الكلاس
        ReportsModule, // دمج وظائف توليد التقارير الدورية (حضور، درجات) في هذا الكلاس
        HolidaysModule, // دمج وظائف إدارة العطلات الرسمية وإجازات الطلاب في هذا الكلاس
        SettingsModule // دمج وظائف التحكم في إعدادات النظام البرمجية من خلال واجهة الأدمن
    implements AdminRepository { // التأكيد على أن هذا الكلاس يحقق وينفذ كافة المهام المحددة في الواجهة AdminRepository

  final SupabaseClient _supabase = Supabase.instance.client; // تهيئة نسخة خاصة من عميل سوبابيس للتواصل مع الخادم

  @override // إعادة تعريف خاصية الوصول لعميل سوبابيس المطلوبة من قبل الوحدات (Modules) المدمجة
  SupabaseClient get supabase => _supabase; // توفير عميل سوبابيس لكافة الوحدات المدمجة لضمان استخدام اتصال واحد موحد
} // نهاية تعريف كلاس SupabaseAdminRepository المسؤول عن إدارة كافة عمليات الأدمن في النظام
